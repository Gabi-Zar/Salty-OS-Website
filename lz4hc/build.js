import { execFileSync } from "node:child_process";
import { access, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
export const OUTPUT = path.join(__dirname, "../src/scripts/common/lz4hc-wasm.js");
const LZ4_REPOSITORY = "https://github.com/lz4/lz4";

const exists = (file) =>
    access(file).then(
        () => true,
        () => false,
    );

function run(command, args, options = {}) {
    try {
        return execFileSync(command, args, { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"], ...options });
    } catch (err) {
        if (err.code === "ENOENT") throw new Error(`lz4hc: "${command}" was not found`, { cause: err });
        throw new Error(`lz4hc: ${command} ${args.slice(0, 3).join(" ")} failed`, { cause: err });
    }
}

function latestTag() {
    const tags = run("git", ["ls-remote", "--tags", "--refs", "--sort=-v:refname", LZ4_REPOSITORY, "v*"])
        .split("\n")
        .map((line) => line.split("refs/tags/")[1])
        .filter((tag) => /^v\d+\.\d+\.\d+$/.test(tag));
    if (!tags.length) throw new Error("lz4hc: no release tag found in the LZ4 repository");
    return tags[0];
}

export async function buildLz4hc() {
    if (await exists(OUTPUT)) return;

    const tag = process.env.LZ4_TAG || latestTag();
    const work = await mkdtemp(path.join(tmpdir(), "lz4hc-"));
    try {
        console.log(`lz4hc: building LZ4 ${tag} for WebAssembly`);
        const lz4 = path.join(work, "lz4");
        run("git", ["-c", "advice.detachedHead=false", "clone", "--quiet", "--depth", "1", "--branch", tag, LZ4_REPOSITORY, lz4]);

        const wasm = path.join(work, "lz4hc.wasm");
        run(process.env.CLANG || "clang", [
            "--target=wasm32",
            "-O3",
            "-ffreestanding",
            "-nostdlib",
            "-mbulk-memory",
            `-I${path.join(__dirname, "stubs")}`,
            `-I${path.join(lz4, "lib")}`,
            "-DLZ4HC_HEAPMODE=0",
            path.join(__dirname, "lz4hc_wrapper.c"),
            path.join(lz4, "lib/lz4.c"),
            path.join(lz4, "lib/lz4hc.c"),
            "-o",
            wasm,
            "-Wl,--no-entry",
            "-Wl,--gc-sections",
            "-Wl,--strip-all",
            "-Wl,-z,stack-size=262144",
            ...["salty_src", "salty_dst", "salty_max_input", "salty_max_output", "salty_compress_hc", "salty_decompress"].map((name) => `-Wl,--export=${name}`),
        ]);

        const base64 = (await readFile(wasm)).toString("base64");
        const license = (await readFile(path.join(lz4, "lib/LICENSE"), "utf8")).trim();
        await writeFile(OUTPUT, `// Generated by lz4hc/build.js from lz4hc/lz4hc_wrapper.c + LZ4 ${tag}.\n/*!\n${license}\n*/\nexport default "${base64}";\n`);
        console.log(`lz4hc: ${path.relative(process.cwd(), OUTPUT)} written (${(base64.length / 1024).toFixed(0)} KiB)`);
    } finally {
        await rm(work, { recursive: true, force: true });
    }
}
